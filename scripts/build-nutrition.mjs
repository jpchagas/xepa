// Downloads the nutrition facts for every TabNut id used in
// src/data/swapGroups.js and writes src/data/nutrition.js.
//
//   npm run nutrition
//
// Run it after adding products to swapGroups.js. The output is
// committed, so the app never calls TabNut at runtime.

// Node
import { writeFileSync } from 'node:fs'

// Data
import SWAP_GROUPS from '../src/data/swapGroups.js'


const BASE_URL = 'https://tabnut.dis.epm.br'
const OUTPUT = new URL('../src/data/nutrition.js', import.meta.url)

// Be gentle with the university's server.
const DELAY_MS = 500

// TabNut row label -> field (values per 100 g).
const FIELDS = {
  'Valor energético (kcal)': 'kcal',
  'Proteína': 'protein',
  'Carboidratos (por diferença)': 'carbs',
  'Gorduras totais': 'fat',
  'Fibra alimentar': 'fiber',
  'Vitamina A (atividade equivalente de retinol)': 'vitaminA',
  'Vitamina C, ácido ascórbico total': 'vitaminC',
  'Potássio': 'potassium',
  'Ferro': 'iron',
  'Cálcio': 'calcium'
}

const REQUIRED = ['kcal', 'protein', 'carbs', 'fat', 'fiber']


const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))

const stripTags = html =>
  html
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

async function fetchText(path) {
  const response = await fetch(`${BASE_URL}${path}`, {
    headers: { 'User-Agent': 'XepaNutritionBuilder/1.0' }
  })

  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`)

  return response.text()
}


// Detail URLs need the slug: /alimento/11354/batata-branca-...
async function loadSlugs() {
  const html = await fetchText('/Alimento')

  return new Map(
    [...html.matchAll(/href="\/alimento\/(\d+)\/([^"]+)"/g)]
      .map(([, id, slug]) => [id, slug])
  )
}


function parseFood(html) {
  const values = {}

  for (const [, row] of html.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)) {
    const cells = [...row.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)]
      .map(([, cell]) => stripTags(cell))

    // [label, unit, per 100 g, ...household measures]
    const field = FIELDS[cells[0]]

    if (field && cells.length >= 3) {
      const value = Number(cells[2])

      if (Number.isFinite(value)) values[field] = value
    }
  }

  // <meta name="description" content="Batata, branca, polpa e pele, cru" />
  const title = html.match(/<meta name="description" content="([^"]+)"/)?.[1]

  return { title, values }
}


const ids = [
  ...new Set(
    SWAP_GROUPS.flatMap(group => group.products.map(product => product.tabnut))
  )
].sort()

console.log(`Fetching ${ids.length} TabNut foods...`)

const slugs = await loadSlugs()
const foods = {}

for (const id of ids) {
  const slug = slugs.get(id)

  if (!slug) throw new Error(`TabNut id ${id} not found in the food list`)

  const { title, values } = parseFood(await fetchText(`/alimento/${id}/${slug}`))

  const missing = REQUIRED.filter(field => values[field] === undefined)

  if (missing.length > 0) {
    throw new Error(`TabNut ${id} (${slug}) is missing ${missing.join(', ')}`)
  }

  foods[id] = { food: title ?? slug.replace(/-/g, ' '), ...values }

  console.log(`  ${id} ${foods[id].food}`)

  await sleep(DELAY_MS)
}


const header = `// GENERATED by scripts/build-nutrition.mjs — do not edit by hand.
// Run \`npm run nutrition\` after changing src/data/swapGroups.js.
//
// Values per 100 g of the raw food, keyed by TabNut id.
// Source: Tabela de Composição Química dos Alimentos - TABNUT
// (EPM/Unifesp, 2014), based on USDA Standard Reference 25.
// https://tabnut.dis.epm.br · DOI: https://doi.org/10.5281/zenodo.13711978
//
// Units: kcal; protein, carbs, fat, fiber in g; vitaminA in µg RAE;
// vitaminC, potassium, iron, calcium in mg.
`

writeFileSync(
  OUTPUT,
  `${header}\nconst NUTRITION = ${JSON.stringify(foods, null, 2)}\n\nexport default NUTRITION\n`
)

console.log(`Wrote ${Object.keys(foods).length} foods to src/data/nutrition.js`)
